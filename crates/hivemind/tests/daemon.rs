//! Daemon integration: two clients, remember/recall/show/changes_since, lock exclusivity.
//! Also asserts HiveMcp tool declaration order via generated `*_tool_attr` helpers.

use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::thread;
use std::time::{Duration, Instant};

use hivemind::client::Client;
use hivemind::mcp::HiveMcp;
use hivemind::protocol;
use hivemind_engine::{Durability, Error, Options, Store};
use serde_json::json;

/// Force both package binaries to be built for this integration test target.
fn ensure_bins_built() -> (&'static str, &'static str) {
    let daemon = env!("CARGO_BIN_EXE_hivemindd");
    let cli = env!("CARGO_BIN_EXE_hivemind");
    assert!(
        Path::new(daemon).is_file(),
        "missing hivemindd binary at {daemon}"
    );
    assert!(Path::new(cli).is_file(), "missing hivemind binary at {cli}");
    (daemon, cli)
}

/// Owns a `hivemindd` child and kills/waits it on drop so tests never leave orphans.
struct DaemonGuard {
    child: Child,
    dir: PathBuf,
}

impl DaemonGuard {
    fn spawn(dir: &Path, idle_timeout_secs: u64) -> Self {
        let (bin, _cli) = ensure_bins_built();
        let child = Command::new(bin)
            .arg("--dir")
            .arg(dir)
            .arg("--no-fsync")
            .arg("--idle-timeout")
            .arg(idle_timeout_secs.to_string())
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .spawn()
            .expect("spawn hivemindd");
        let mut guard = Self {
            child,
            dir: dir.to_path_buf(),
        };
        guard.wait_ready(Duration::from_secs(5));
        guard
    }

    fn wait_ready(&mut self, timeout: Duration) {
        let sock = protocol::socket_path(&self.dir);
        let deadline = Instant::now() + timeout;
        while Instant::now() < deadline {
            if sock.exists() && Client::connect(&self.dir).is_ok() {
                return;
            }
            if let Ok(Some(status)) = self.child.try_wait() {
                panic!("hivemindd exited before becoming ready: {status}");
            }
            thread::sleep(Duration::from_millis(25));
        }
        panic!("hivemindd did not become ready at {}", sock.display());
    }
}

impl Drop for DaemonGuard {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}

#[test]
fn hive_mcp_tool_names_in_declaration_order() {
    // Generated by `#[tool]` / `#[tool_router]`; declaration order is the contract
    // for docs and get_info instructions (list_all() sorts alphabetically).
    let tools = [
        HiveMcp::remember_tool_attr(),
        HiveMcp::recall_tool_attr(),
        HiveMcp::show_tool_attr(),
        HiveMcp::retract_tool_attr(),
        HiveMcp::forget_tool_attr(),
        HiveMcp::feedback_tool_attr(),
        HiveMcp::promote_tool_attr(),
        HiveMcp::changes_since_tool_attr(),
    ];
    let names: Vec<&str> = tools.iter().map(|t| t.name.as_ref()).collect();
    assert_eq!(
        names,
        vec![
            "remember",
            "recall",
            "show",
            "retract",
            "forget",
            "feedback",
            "promote",
            "changes_since",
        ]
    );
}

#[test]
fn two_clients_round_trip_and_lock_stays_exclusive() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();
    // Match production-ish idle; Drop still kills promptly on cleanup.
    let _daemon = DaemonGuard::spawn(dir, 30);

    let mut a = Client::connect(dir).expect("client a");
    let mut b = Client::connect(dir).expect("client b");
    assert_eq!(a.hello.protocol, protocol::PROTOCOL);
    assert_eq!(a.hello.store_id, b.hello.store_id);

    // Leave the workers waiting on an empty socket. On macOS an accepted
    // socket can inherit the listener's nonblocking flag and otherwise exit.
    thread::sleep(Duration::from_millis(150));

    let remembered = a
        .call(
            "remember",
            json!({
                "statement": "Daemon clients share one store over the Unix socket",
                "kind": "fact",
                "scope": "project:acme/daemon",
            }),
        )
        .expect("remember");
    let claim = remembered["claim"].as_str().expect("claim id").to_owned();
    let offset = remembered["offset"].as_u64().expect("offset");

    let recalled = b
        .call(
            "recall",
            json!({
                "query": "Unix socket store",
                "min_offset": offset,
            }),
        )
        .expect("recall");
    let cards = recalled["cards"].as_array().expect("cards");
    assert!(
        cards.iter().any(|c| c["id"] == claim),
        "recall from second client must see the write: {recalled}"
    );

    let shown = a
        .call(
            "show",
            json!({
                "id": claim,
                "min_offset": offset,
            }),
        )
        .expect("show");
    assert_eq!(shown["id"], claim);
    assert!(
        shown["statement"]
            .as_str()
            .unwrap_or("")
            .contains("Unix socket")
    );

    let changes = b
        .call(
            "changes_since",
            json!({
                "from": 0,
                "limit": 50,
            }),
        )
        .expect("changes_since");
    let events = changes["events"].as_array().expect("events");
    assert!(
        events
            .iter()
            .any(|row| { row["event"]["body"]["claim"].as_str() == Some(claim.as_str()) }),
        "change feed must include the remember: {changes}"
    );
    assert!(changes["next_offset"].as_u64().unwrap() > offset);

    // Daemon holds the store LOCK; a second direct open must fail.
    let locked = Store::open(
        dir,
        Options {
            durability: Durability::NoFsync,
            ..Options::default()
        },
    );
    assert!(
        matches!(locked, Err(Error::Locked(_))),
        "expected Locked while daemon owns the store, got {locked:?}"
    );
}

#[test]
fn shutdown_rpc_stops_daemon_and_cleans_socket() {
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();
    let mut daemon = DaemonGuard::spawn(dir, 30);
    let sock = protocol::socket_path(dir);
    assert!(sock.exists());

    let mut client = Client::connect(dir).expect("connect");
    let resp = client.call("shutdown", json!({})).expect("shutdown");
    assert_eq!(resp["stopping"], true);

    let deadline = Instant::now() + Duration::from_secs(5);
    loop {
        if let Ok(Some(status)) = daemon.child.try_wait() {
            assert!(status.success(), "daemon exited with {status}");
            break;
        }
        assert!(
            Instant::now() < deadline,
            "daemon did not exit after shutdown RPC"
        );
        thread::sleep(Duration::from_millis(25));
    }
    assert!(
        !sock.exists(),
        "socket file should be removed on clean exit"
    );
}

#[test]
fn mcp_stdio_reconnects_after_daemon_restart_and_isolates_actors() {
    use std::io::{BufRead, BufReader, Write};

    let (_daemon_bin, cli_bin) = ensure_bins_built();
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();

    // Seed a stale socket file to verify connect_or_spawn recovers cleanly.
    let run_dir = dir.join(protocol::RUN_DIR);
    std::fs::create_dir_all(&run_dir).unwrap();
    std::fs::write(protocol::socket_path(dir), b"stale").unwrap();

    let mut mcp = Command::new(cli_bin)
        .args(["mcp", "--dir"])
        .arg(dir)
        .env("HIVEMIND_AGENT", "copilot-cli")
        .env("HIVEMIND_PRINCIPAL", "alice")
        .env("HIVEMIND_SESSION", "sess-mcp-1")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn()
        .expect("spawn hivemind mcp");
    let mut stdin = mcp.stdin.take().unwrap();
    let mut stdout = BufReader::new(mcp.stdout.take().unwrap());

    let send = |stdin: &mut std::process::ChildStdin, msg: serde_json::Value| {
        let mut s = serde_json::to_string(&msg).unwrap();
        s.push('\n');
        stdin.write_all(s.as_bytes()).unwrap();
        stdin.flush().unwrap();
    };
    let recv = |stdout: &mut BufReader<std::process::ChildStdout>| -> serde_json::Value {
        let mut line = String::new();
        stdout.read_line(&mut line).unwrap();
        serde_json::from_str(&line).expect("valid json-rpc response")
    };

    // MCP initialize handshake.
    send(
        &mut stdin,
        json!({
            "jsonrpc": "2.0",
            "id": 1,
            "method": "initialize",
            "params": {
                "protocolVersion": "2025-03-26",
                "capabilities": {},
                "clientInfo": { "name": "test", "version": "0.1" }
            }
        }),
    );
    let init = recv(&mut stdout);
    assert!(init["result"]["serverInfo"]["name"].is_string(), "{init}");
    send(
        &mut stdin,
        json!({ "jsonrpc": "2.0", "method": "notifications/initialized" }),
    );

    // 1. Write a claim with citation + quote via MCP.
    send(
        &mut stdin,
        json!({
            "jsonrpc": "2.0",
            "id": 2,
            "method": "tools/call",
            "params": {
                "name": "remember",
                "arguments": {
                    "statement": "MCP reconnects seamlessly across daemon restarts",
                    "kind": "fact",
                    "scope": "project:acme/mcp",
                    "cites": ["src/mcp.rs:1-10"],
                    "quotes": ["daemon closed the connection"]
                }
            }
        }),
    );
    let rem_resp = recv(&mut stdout);
    let rem_text = rem_resp["result"]["content"][0]["text"]
        .as_str()
        .expect("remember json text");
    let rem_val: serde_json::Value = serde_json::from_str(rem_text).unwrap();
    let claim_id = rem_val["claim"].as_str().unwrap().to_owned();
    let offset = rem_val["offset"].as_u64().unwrap();

    // 2. Shut down the spawned daemon behind MCP's back!
    let mut killer = Client::connect(dir).expect("connect to spawned daemon");
    killer.call("shutdown", json!({})).expect("shutdown");
    drop(killer);
    let deadline = Instant::now() + Duration::from_secs(5);
    while protocol::socket_path(dir).exists() && Instant::now() < deadline {
        thread::sleep(Duration::from_millis(25));
    }

    // 3. Call recall via the SAME MCP session — must auto-respawn daemon & succeed!
    send(
        &mut stdin,
        json!({
            "jsonrpc": "2.0",
            "id": 3,
            "method": "tools/call",
            "params": {
                "name": "recall",
                "arguments": {
                    "query": "reconnects seamlessly",
                    "min_offset": offset
                }
            }
        }),
    );
    let rec_resp = recv(&mut stdout);
    assert_ne!(rec_resp["result"]["isError"], true, "{rec_resp}");
    let rec_text = rec_resp["result"]["content"][0]["text"].as_str().unwrap();
    let rec_val: serde_json::Value = serde_json::from_str(rec_text).unwrap();
    assert!(
        rec_val["cards"]
            .as_array()
            .unwrap()
            .iter()
            .any(|c| c["id"] == claim_id),
        "recalled after daemon respawn: {rec_val}"
    );

    // 4. Verify actor principal/agent/session were forwarded (not daemon's env).
    send(
        &mut stdin,
        json!({
            "jsonrpc": "2.0",
            "id": 4,
            "method": "tools/call",
            "params": {
                "name": "show",
                "arguments": { "id": claim_id }
            }
        }),
    );
    let show_resp = recv(&mut stdout);
    let show_val: serde_json::Value =
        serde_json::from_str(show_resp["result"]["content"][0]["text"].as_str().unwrap()).unwrap();
    assert_eq!(show_val["author"]["principal"], "alice");
    assert_eq!(show_val["author"]["agent"], "copilot-cli");
    assert_eq!(show_val["author"]["session"], "sess-mcp-1");
    assert_eq!(show_val["provenance"]["citations"][0]["path"], "src/mcp.rs");

    // Clean up both the MCP shim and the respawned daemon.
    drop(stdin);
    let _ = mcp.wait();
    if let Ok(mut c) = Client::connect(dir) {
        let _ = c.call("shutdown", json!({}));
    }
}

#[test]
fn cli_via_daemon_forwards_quotes_cites_and_here_context() {
    let (_daemon_bin, cli_bin) = ensure_bins_built();
    let tmp = tempfile::tempdir().unwrap();
    let dir = tmp.path();
    let _daemon = DaemonGuard::spawn(dir, 30);

    let out = Command::new(cli_bin)
        .args([
            "--dir",
            dir.to_str().unwrap(),
            "--json",
            "remember",
            "CLI daemon path preserves quotes and conditions",
            "--scope",
            "project:acme/cli",
            "--when",
        ])
        .arg(format!("os={}", std::env::consts::OS))
        .args([
            "--quote",
            "exact error excerpt",
            "--cite",
            "src/main.rs:10-20",
        ])
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    let rem: serde_json::Value = serde_json::from_slice(&out.stdout).unwrap();
    let id = rem["claim"].as_str().unwrap();

    let show_out = Command::new(cli_bin)
        .args(["--dir", dir.to_str().unwrap(), "--json", "show", id])
        .output()
        .unwrap();
    assert!(show_out.status.success());
    let detail: serde_json::Value = serde_json::from_slice(&show_out.stdout).unwrap();
    assert_eq!(detail["provenance"]["citations"][0]["path"], "src/main.rs");
    assert_eq!(
        detail["provenance"]["evidence"][0]["quote"],
        "exact error excerpt"
    );

    let rec_out = Command::new(cli_bin)
        .args([
            "--dir",
            dir.to_str().unwrap(),
            "--json",
            "recall",
            "preserves quotes",
            "--here",
        ])
        .output()
        .unwrap();
    assert!(rec_out.status.success());
    let rec: serde_json::Value = serde_json::from_slice(&rec_out.stdout).unwrap();
    assert_eq!(rec["cards"][0]["id"], id);
    assert_eq!(rec["cards"][0]["applicability"]["state"], "match");

    let backup_dir = tempfile::tempdir().unwrap();
    let backup_target = backup_dir.path().join("snap");
    let bk_out = Command::new(cli_bin)
        .args([
            "--dir",
            dir.to_str().unwrap(),
            "--json",
            "backup",
            backup_target.to_str().unwrap(),
        ])
        .output()
        .unwrap();
    assert!(
        bk_out.status.success(),
        "{}",
        String::from_utf8_lossy(&bk_out.stderr)
    );
    let bk: serde_json::Value = serde_json::from_slice(&bk_out.stdout).unwrap();
    assert!(bk["segments"].as_u64().unwrap() >= 1);
}
